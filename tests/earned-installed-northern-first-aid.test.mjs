import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {decodeSave,encodeSave} from '../game/save.js';
import {completeHiredNorthernMission} from './fresh-northern-command.mjs';

test('earned installed Salta casualty receives timely finite aid before the real Yatasto continuation',()=>{
 const raw=gunzipSync(readFileSync(new URL('./fixtures/earned-installed-salta-first-aid.save.json.gz',import.meta.url)));
 const provenance=JSON.parse(readFileSync(new URL('./fixtures/earned-installed-salta-first-aid.provenance.json',import.meta.url)));
 assert.equal(createHash('sha256').update(raw).digest('hex'),provenance.sha256);
 assert.equal(raw.length,provenance.rawBytes);
 const start=decodeSave(raw.toString('utf8')).campaign,before=structuredClone(start),events=[];
 assert.equal(start.contentCampaign.package.id,'granaderos');
 assert.deepEqual([start.hour,start.secondOfHour],[961,1565]);
 assert.equal(start.operativeState[9].hp,10);assert.equal(start.operativeState[9].bleeding,5);
 assert.equal(start.operativeState[1].medkits,0);assert.equal(start.operativeState[146].medkits,0);
 const body=campaign=>campaign.sectorStates.salta.units.find(unit=>unit.id==='enemy-1');
 assert.equal(body(start).hp,0);assert.equal(body(start).medkits,2);
 const result=completeHiredNorthernMission(start,{routeKind:'stock',report:event=>events.push(event)});
 assert.deepEqual(start,before,'planning and orders must not mutate the earned input');
 const collection=events.filter(event=>event.event==='northernMissionDressingsCollected');
 assert.deepEqual(collection,[{event:'northernMissionDressingsCollected',id:1,sector:'salta',count:2,sourceKey:'["body","enemy-1","medkits"]'}]);
 const aid=events.filter(event=>event.event==='northernMissionFirstAid');
 assert.equal(aid.length,1);assert.deepEqual(aid[0].ids,[1,9]);
 assert.equal(aid[0].elapsedSeconds,3);assert.equal(aid[0].actions,2);
 assert.deepEqual(aid[0].treatedIds,['9']);assert.equal(aid[0].stoppedReason,null);
 assert.equal(body(result).medkits,0);assert.equal(result.operativeState[1].medkits,1);
 for(const [id,record]of Object.entries(before.operativeState))if(!record.alive)assert.equal(result.operativeState[id].alive,false,'actual prior losses remain permanent');
 assert.equal(result.operativeState[9].alive,true);assert.equal(result.operativeState[9].hp,15);assert.equal(result.operativeState[9].bleeding,0);
 assert.equal(result.phase,3);assert.equal(result.missions.yatasto.completed,true);
 assert.equal(result.flags.northPact,true);assert.equal(result.flags.partisanSupply,true);
 assert.equal(result.completed,false);assert.equal(result.defeated,false);assert.equal(result.pendingBattle,null);
 assert.deepEqual([result.hour,result.secondOfHour],[966,1679]);
 assert.equal(events.find(event=>event.event==='northernMissionPact').cost,300);
 assert.deepEqual(decodeSave(encodeSave(result)).campaign,result,'the actual continued mission admits the official save');
});
