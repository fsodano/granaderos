import test from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtemp,mkdir,writeFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {buildIdentity} from '../tools/build-identity.mjs';
test('game, editor, tools and public art changes each produce a different source identity',async()=>{
 const root=await mkdtemp(join(tmpdir(),'granaderos-build-id-'));
 try{
  await writeFile(join(root,'package.json'),JSON.stringify({version:'test'}));
  for(const dir of ['game','web/app','web/public/art','tools','web/dist','web/node_modules','campaigns/example/assets'])await mkdir(join(root,dir),{recursive:true});
  let before=await buildIdentity(root);assert.equal(before.version,'test');assert.equal(before.revision,null);
  for(const file of ['game/rules.js','web/app/editor.tsx','tools/audit.mjs','web/public/art/building.png','campaigns/example/manifest.json','campaigns/example/assets/portrait.png']){
   await writeFile(join(root,file),'changed source');const after=await buildIdentity(root);assert.notEqual(after.id,before.id);before=after;
  }
  await writeFile(join(root,'web/dist/output.js'),'compiled output');await writeFile(join(root,'web/node_modules/dependency.js'),'installed dependency');
  assert.deepEqual(await buildIdentity(root),before,'outputs and installed modules cannot make identity depend on prior builds');
  await writeFile(join(root,'web/next-env.d.ts'),'generated route declarations');
  assert.deepEqual(await buildIdentity(root),before,'a clean build can generate route declarations without changing its identity');
  await writeFile(join(root,'web/next-env.d.ts'),'updated generated declarations');
  assert.deepEqual(await buildIdentity(root),before);
  await rm(join(root,'web/next-env.d.ts'));
  assert.deepEqual(await buildIdentity(root),before);
 }finally{await rm(root,{recursive:true,force:true});}
});
test('Python bytecode changes keep identity while dirty Python and game sources change it',async()=>{
 const root=await mkdtemp(join(tmpdir(),'granaderos-build-id-python-'));
 try{
  await writeFile(join(root,'package.json'),JSON.stringify({version:'test'}));
  await mkdir(join(root,'game'),{recursive:true});
  await mkdir(join(root,'tools/characters-3d'),{recursive:true});
  await writeFile(join(root,'game/rules.js'),'export const range=10;');
  await writeFile(join(root,'tools/characters-3d/shape.py'),'scale = 1\n');
  execFileSync('git',['init','--quiet',root]);
  execFileSync('git',['-C',root,'add','package.json','game/rules.js','tools/characters-3d/shape.py']);
  execFileSync('git',['-C',root,'-c','user.name=Build identity test','-c','user.email=build-identity@example.invalid','commit','--quiet','-m','Declare source inputs']);
  const before=await buildIdentity(root);assert.equal(before.version,'test');assert.match(before.revision,/^[0-9a-f]{40}$/);
  await mkdir(join(root,'tools/characters-3d/__pycache__'),{recursive:true});
  await writeFile(join(root,'tools/characters-3d/__pycache__/shape.cpython-313.pyc'),'first generated bytecode');
  assert.deepEqual(await buildIdentity(root),before,'test-created Python bytecode is not a source input');
  await writeFile(join(root,'tools/characters-3d/__pycache__/shape.cpython-313.pyc'),'regenerated bytecode');
  await writeFile(join(root,'tools/characters-3d/__pycache__/other.cpython-313.pyc'),'another generated module');
  assert.deepEqual(await buildIdentity(root),before,'changed and newly generated bytecode keep the complete identity');
  await writeFile(join(root,'tools/characters-3d/shape.py'),'scale = 2\n');
  const pythonChanged=await buildIdentity(root);assert.notEqual(pythonChanged.source,before.source);assert.notEqual(pythonChanged.id,before.id);
  assert.equal(pythonChanged.revision,before.revision);assert.equal(pythonChanged.version,before.version);
  await writeFile(join(root,'game/rules.js'),'export const range=11;');
  const gameChanged=await buildIdentity(root);assert.notEqual(gameChanged.source,pythonChanged.source);assert.notEqual(gameChanged.id,pythonChanged.id);
  assert.equal(gameChanged.revision,before.revision);assert.equal(gameChanged.version,before.version);
 }finally{await rm(root,{recursive:true,force:true});}
});
