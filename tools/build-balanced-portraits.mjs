// Rebuild the balanced portrait expansion from its individually generated art.
import {access,readFile,writeFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(resolve(root,'web/package.json'));
const sharp=require('sharp');
const rows=JSON.parse(await readFile(resolve(root,'assets/prompts/balanced-portraits.json'),'utf8'));
if(rows.length!==122||new Set(rows.map(row=>row.id)).size!==rows.length)throw Error('Expected 122 distinct portrait expansion IDs.');
// Fail before writing if generation has not finished.
for(const row of rows)await access(resolve(root,row.source));
const manifest=[];
for(const row of rows){
 const output=await sharp(resolve(root,row.source)).resize(384,384,{fit:'cover'}).webp({quality:86}).toBuffer();
 const filename=`${row.id}.webp`;
 for(const base of ['assets/web','web/public/art']){
  await mkdir(resolve(root,base),{recursive:true});
  await writeFile(resolve(root,base,filename),output);
 }
 manifest.push({id:row.id,file:`/art/${filename}`,source:row.source,size:[384,384],bytes:output.length,sha256:createHash('sha256').update(output).digest('hex'),fictional:true,method:row.method});
}
for(const base of ['assets/web','web/public/art'])await writeFile(resolve(root,base,'balanced-portraits.json'),JSON.stringify(manifest,null,2)+'\n');
const catalog=rows.map(({id,name,gender,role,skinTone,spriteAppearance})=>({id,name,gender,role,skinTone,spriteAppearance,spriteSkinTone:skinTone,src:`/art/${id}.webp`}));
await writeFile(resolve(root,'game/portrait-expansion.js'),'// Generated by tools/build-balanced-portraits.mjs from the saved art prompts.\nexport const BALANCED_PORTRAITS='+JSON.stringify(catalog,null,2)+';\n');
console.log(`Built ${manifest.length} distinct portraits for the balanced chooser.`);
