// Publish the validated staging library and its small runtime layout index.
// Partial publication is an intermediate migration state. The separate complete
// coverage gate must pass before the sprite replacement can be declared done.
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {SPRITE_APPEARANCES} from '../game/sprite-appearances.js';
import {SPRITE_SEQUENCES,CIVILIAN_SPRITE_SEQUENCES} from '../game/sprite-state.js';

const staging=resolve('assets/previews/illustrated-sprites/packed');
const manifest=JSON.parse(await readFile(resolve(staging,'manifest.json'),'utf8'));
const index={};
const complete=Object.keys(SPRITE_APPEARANCES).every(appearance=>(appearance==='civilian'?CIVILIAN_SPRITE_SEQUENCES:SPRITE_SEQUENCES).every(sequence=>manifest.atlases[`${appearance}-${sequence}`]));
// Validate every byte before publishing any atlas.
for(const [name,entry] of Object.entries(manifest.atlases)){
 const bytes=await readFile(resolve(staging,entry.file));
 if(createHash('sha256').update(bytes).digest('hex')!==entry.sha256||entry.records.length!==8*entry.framesPerDirection)throw Error(`Invalid staged atlas ${name}`);
 const {file,cell,anchor,logicalCell,framesPerDirection,fps,size}=entry;
 index[name]={file,cell,anchor,logicalCell,framesPerDirection,fps,size};
}
for(const directory of ['assets/web/illustrated','web/public/art/illustrated']){
 await mkdir(directory,{recursive:true});
 for(const entry of Object.values(index))await copyFile(resolve(staging,entry.file),resolve(directory,entry.file));
 await writeFile(resolve(directory,'manifest.json'),JSON.stringify({...manifest,status:complete?'complete':'partial-migration'},null,2)+'\n');
}
const header='// Generated by tools/publish-illustrated-sprites.mjs. Do not edit by hand.\n/** @type {Record<string,{file:string,cell:number,anchor:number[],logicalCell:number,framesPerDirection:number,fps:number,size:number[]}>} */\n';
await writeFile('game/illustrated-sprite-atlases.js',header+'export const ILLUSTRATED_SPRITE_ATLASES = '+JSON.stringify(index,null,2)+';\n');
console.log(`Published ${Object.keys(index).length} illustrated atlases. Full-coverage audit still required.`);
